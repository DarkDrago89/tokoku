import Link from "next/link";
import { notFound } from "next/navigation";
import { Cake, Mail, MapPin, Pencil, Receipt, Tag as TagIcon, Megaphone, StickyNote } from "lucide-react";
import { PageHeader } from "@/components/ui/PageHeader";
import { ButtonLink } from "@/components/ui/Button";
import { Card, SectionTitle } from "@/components/ui/Card";
import { Avatar } from "@/components/ui/Avatar";
import { Badge } from "@/components/ui/Badge";
import { requireSession } from "@/lib/session";
import { getStoreSettings, getTemplates } from "@/lib/store";
import { can } from "@/lib/permissions";
import { getCustomerForStore } from "@/features/customers/service";
import { CustomerStatusBadges } from "@/features/customers/StatusBadge";
import { DeleteCustomerButton } from "@/features/customers/DeleteCustomerButton";
import { getTimeline } from "@/features/interactions/service";
import { Timeline } from "@/features/interactions/Timeline";
import { AddTaskButton, LogInteractionButton } from "@/features/interactions/QuickForms";
import { listOpenTasksForCustomer } from "@/features/tasks/service";
import { TaskItem } from "@/features/tasks/TaskItem";
import { WhatsAppButton } from "@/features/templates/SendWhatsAppSheet";
import { formatPhone } from "@/lib/domain/phone";
import { formatDate, formatRupiah, relativeDays } from "@/lib/domain/format";
import { jakartaToday, num } from "@/lib/utils";

export default async function CustomerDetailPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const s = await requireSession();
  const c = await getCustomerForStore(s.storeId, id);
  if (!c) notFound();
  const [{ inactiveDays }, templates, timeline, tasks] = await Promise.all([
    getStoreSettings(s.storeId),
    getTemplates(s.storeId),
    getTimeline(s.storeId, c.id),
    listOpenTasksForCustomer(s.storeId, c.id),
  ]);
  const today = jakartaToday();
  const now = new Date();
  const waCustomer = { id: c.id, name: c.name, phone: c.phone };

  return (
    <>
      <PageHeader
        title={c.name}
        back="/pelanggan"
        action={
          <ButtonLink href={`/pelanggan/${c.id}/ubah`} variant="ghost" size="sm" aria-label="Ubah">
            <Pencil className="h-4 w-4" /> <span className="hidden sm:inline">Ubah</span>
          </ButtonLink>
        }
      />

      <Card className="mb-4 p-4">
        <div className="flex items-center gap-3">
          <Avatar name={c.name} size={52} />
          <div className="min-w-0">
            <a href={`tel:+${c.phone}`} className="tabular text-lg font-medium">
              {formatPhone(c.phone)}
            </a>
            <div className="mt-1 flex flex-wrap gap-1.5">
              <CustomerStatusBadges c={c} inactiveDays={inactiveDays} now={now} />
              {c.tags.map((t) => (
                <Badge key={t.tagId} tone="outline">
                  <TagIcon className="h-3 w-3" /> {t.tag.name}
                </Badge>
              ))}
            </div>
          </div>
        </div>
        <WhatsAppButton customer={waCustomer} templates={templates} size="lg" className="mt-4" />
        <div className="mt-2 grid grid-cols-3 gap-2">
          <ButtonLink href={`/pesanan/baru?pelanggan=${c.id}`} variant="secondary">
            <Receipt className="h-4 w-4" /> Pesanan
          </ButtonLink>
          <LogInteractionButton customerId={c.id} />
          <AddTaskButton customerId={c.id} />
        </div>
      </Card>

      <div className="mb-6 grid grid-cols-3 divide-x divide-zinc-200 rounded-2xl border border-zinc-200 text-center">
        <Stat label="Total belanja" value={formatRupiah(num(c.totalSpent))} />
        <Stat label="Pesanan selesai" value={String(c.orderCount)} />
        <Stat label="Terakhir beli" value={c.lastOrderAt ? relativeDays(c.lastOrderAt, now) : "–"} />
      </div>

      {tasks.length > 0 && (
        <section className="mb-6">
          <SectionTitle count={tasks.length}>Tugas follow-up</SectionTitle>
          <ul className="space-y-2">
            {tasks.map((t) => (
              <TaskItem
                key={t.id}
                showCustomer={false}
                templates={templates}
                task={{
                  id: t.id,
                  title: t.title,
                  notes: t.notes,
                  autoGenerated: t.autoGenerated,
                  overdue: t.dueDate < today,
                  dueLabel: t.dueDate < today ? `Terlambat · ${formatDate(t.dueDate)}` : formatDate(t.dueDate),
                  customer: waCustomer,
                }}
              />
            ))}
          </ul>
        </section>
      )}

      <section className="mb-6">
        <SectionTitle>Riwayat</SectionTitle>
        <Timeline entries={timeline} />
      </section>

      <section className="mb-6">
        <SectionTitle>Info pelanggan</SectionTitle>
        <Card className="divide-y divide-zinc-100 text-sm">
          <Info icon={MapPin} label="Alamat" value={[c.address, c.city].filter(Boolean).join(", ")} />
          <Info icon={Mail} label="Email" value={c.email} />
          <Info icon={Cake} label="Ulang tahun" value={c.birthday ? formatDate(c.birthday) : null} />
          <Info icon={Megaphone} label="Sumber" value={c.source} />
          <Info icon={StickyNote} label="Catatan" value={c.notes} />
          <div className="px-4 py-3 text-xs text-zinc-400">Dicatat sejak {formatDate(c.createdAt)}</div>
        </Card>
      </section>

      {can(s.role, "customer.delete") && (
        <div className="flex justify-center pb-4">
          <DeleteCustomerButton id={c.id} name={c.name} />
        </div>
      )}
      <p className="sr-only">
        <Link href="/pelanggan">Kembali ke daftar</Link>
      </p>
    </>
  );
}

function Stat({ label, value }: { label: string; value: string }) {
  return (
    <div className="px-2 py-3">
      <p className="tabular truncate font-semibold">{value}</p>
      <p className="text-xs text-zinc-500">{label}</p>
    </div>
  );
}

function Info({ icon: Icon, label, value }: { icon: React.ElementType; label: string; value?: string | null }) {
  return (
    <div className="flex gap-3 px-4 py-3">
      <Icon className="mt-0.5 h-4 w-4 shrink-0 text-zinc-400" />
      <div className="min-w-0">
        <p className="text-xs text-zinc-500">{label}</p>
        <p className={value ? "whitespace-pre-line text-zinc-900" : "text-zinc-400"}>{value || "Belum diisi"}</p>
      </div>
    </div>
  );
}
