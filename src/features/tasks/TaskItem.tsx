"use client";

import Link from "next/link";
import { useState, useTransition } from "react";
import { Check, Loader2 } from "lucide-react";
import { Sheet } from "@/components/ui/Sheet";
import { Button } from "@/components/ui/Button";
import { Badge } from "@/components/ui/Badge";
import { WhatsAppButton, type TemplateOption } from "@/features/templates/SendWhatsAppSheet";
import { completeTaskAction } from "./actions";

export type TaskView = {
  id: string;
  title: string;
  notes: string | null;
  dueLabel: string;
  overdue?: boolean;
  autoGenerated?: boolean;
  customer: { id: string; name: string; phone: string } | null;
};

/** Kartu tugas dengan tombol WhatsApp dan "Selesai" (alur follow-up harian 5.2). */
export function TaskItem({ task, templates, showCustomer = true }: { task: TaskView; templates: TemplateOption[]; showCustomer?: boolean }) {
  const [open, setOpen] = useState(false);
  const [note, setNote] = useState("");
  const [pending, start] = useTransition();
  const [done, setDone] = useState(false);

  const finish = () =>
    start(async () => {
      await completeTaskAction(task.id, note);
      setDone(true);
      setOpen(false);
    });

  if (done) return null;
  const preferCategory = task.title === "Minta ulasan" ? "Terima kasih" : undefined;

  return (
    <li className="rounded-2xl border border-zinc-200 p-4">
      <div className="flex items-start gap-3">
        <button
          onClick={() => setOpen(true)}
          aria-label={`Tandai selesai: ${task.title}`}
          className="mt-0.5 flex h-6 w-6 shrink-0 items-center justify-center rounded-full border-2 border-zinc-300 hover:border-zinc-900"
        >
          {pending && <Loader2 className="h-3 w-3 animate-spin" />}
        </button>
        <div className="min-w-0 flex-1">
          <p className="font-medium">{task.title}</p>
          {showCustomer && task.customer && (
            <Link href={`/pelanggan/${task.customer.id}`} className="text-sm text-zinc-600 underline-offset-2 hover:underline">
              {task.customer.name}
            </Link>
          )}
          {task.notes && <p className="mt-1 text-sm text-zinc-500">{task.notes}</p>}
          <div className="mt-2 flex flex-wrap items-center gap-2">
            <Badge tone={task.overdue ? "danger" : "neutral"}>{task.dueLabel}</Badge>
            {task.autoGenerated && <Badge tone="outline">Otomatis</Badge>}
          </div>
        </div>
      </div>
      <div className="mt-3 flex gap-2">
        {task.customer && (
          <WhatsAppButton customer={task.customer} templates={templates} size="sm" className="flex-1" label="WhatsApp" preferCategory={preferCategory} />
        )}
        <Button variant="secondary" size="sm" className="flex-1" onClick={() => setOpen(true)}>
          <Check className="h-4 w-4" /> Selesai
        </Button>
      </div>

      <Sheet open={open} onClose={() => setOpen(false)} title="Tandai selesai">
        <p className="mb-3 text-sm text-zinc-600">{task.title}</p>
        <label htmlFor={`note-${task.id}`} className="mb-1.5 block text-sm font-medium">
          Catatan singkat <span className="font-normal text-zinc-400">(opsional)</span>
        </label>
        <textarea
          id={`note-${task.id}`}
          value={note}
          onChange={(e) => setNote(e.target.value)}
          rows={3}
          placeholder="Contoh: sudah dihubungi, mau order minggu depan"
          className="w-full rounded-xl border border-zinc-300 p-3 text-[15px] focus:border-zinc-900 focus:outline-none"
        />
        <Button size="lg" className="mt-4" disabled={pending} onClick={finish}>
          {pending ? <Loader2 className="h-4 w-4 animate-spin" /> : <Check className="h-4 w-4" />} Selesai
        </Button>
      </Sheet>
    </li>
  );
}
