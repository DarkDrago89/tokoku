import Link from "next/link";
import { Cake, CalendarCheck, Clock, PartyPopper, Plus } from "lucide-react";
import { PageHeader } from "@/components/ui/PageHeader";
import { SectionTitle } from "@/components/ui/Card";
import { EmptyState } from "@/components/ui/EmptyState";
import { ButtonLink } from "@/components/ui/Button";
import { Avatar } from "@/components/ui/Avatar";
import { requireSession } from "@/lib/session";
import { getStoreSettings, getTemplates } from "@/lib/store";
import { getToday, type TaskWithCustomer } from "@/features/tasks/service";
import { TaskItem, type TaskView } from "@/features/tasks/TaskItem";
import { WhatsAppButton } from "@/features/templates/SendWhatsAppSheet";
import { formatDate, formatRupiah, relativeDays } from "@/lib/domain/format";
import { num } from "@/lib/utils";

export const metadata = { title: "Hari Ini" };

const longDate = new Intl.DateTimeFormat("id-ID", { timeZone: "Asia/Jakarta", weekday: "long", day: "numeric", month: "long" });

function greeting(now: Date) {
  const h = Number(new Intl.DateTimeFormat("en-GB", { timeZone: "Asia/Jakarta", hour: "numeric", hour12: false }).format(now));
  if (h < 11) return "Selamat pagi";
  if (h < 15) return "Selamat siang";
  if (h < 18) return "Selamat sore";
  return "Selamat malam";
}

function toView(t: TaskWithCustomer, overdue: boolean, today: Date): TaskView {
  const daysLate = Math.round((+today - +t.dueDate) / 86_400_000);
  return {
    id: t.id,
    title: t.title,
    notes: t.notes,
    autoGenerated: t.autoGenerated,
    overdue,
    dueLabel: overdue ? `Terlambat ${daysLate} hari` : "Hari ini",
    customer: t.customer,
  };
}

export default async function TodayPage() {
  const s = await requireSession();
  const now = new Date();
  const { inactiveDays } = await getStoreSettings(s.storeId);
  const [data, templates] = await Promise.all([getToday(s.storeId, now, inactiveDays), getTemplates(s.storeId)]);
  const total = data.overdue.length + data.dueToday.length + data.birthdays.length + data.inactive.length;

  return (
    <>
      <PageHeader
        title={`${greeting(now)}, ${s.name.split(" ")[0]}`}
        subtitle={longDate.format(now)}
        action={
          <ButtonLink href="/tugas/baru" variant="secondary" size="sm">
            <Plus className="h-4 w-4" /> Tugas
          </ButtonLink>
        }
      />

      <div className="mb-6 grid grid-cols-3 gap-2">
        <Counter label="Terlambat" value={data.overdue.length} alert={data.overdue.length > 0} />
        <Counter label="Hari ini" value={data.dueToday.length} />
        <Counter label="Perlu disapa" value={data.birthdays.length + data.inactive.length} />
      </div>

      {total === 0 && (
        <EmptyState
          icon={<PartyPopper className="h-6 w-6" />}
          title="Semua beres untuk hari ini 🎉"
          action={
            <ButtonLink href="/pelanggan" variant="secondary">
              Lihat pelanggan
            </ButtonLink>
          }
        >
          Tidak ada follow-up yang jatuh tempo. Tugas baru akan muncul otomatis setelah pesanan selesai.
        </EmptyState>
      )}

      {data.overdue.length > 0 && (
        <Section title="Terlambat" count={data.overdue.length} icon={Clock}>
          {data.overdue.map((t) => (
            <TaskItem key={t.id} task={toView(t, true, data.today)} templates={templates} />
          ))}
        </Section>
      )}

      {data.dueToday.length > 0 && (
        <Section title="Jatuh tempo hari ini" count={data.dueToday.length} icon={CalendarCheck}>
          {data.dueToday.map((t) => (
            <TaskItem key={t.id} task={toView(t, false, data.today)} templates={templates} />
          ))}
        </Section>
      )}

      {data.birthdays.length > 0 && (
        <Section title="Ulang tahun hari ini" count={data.birthdays.length} icon={Cake}>
          {data.birthdays.map((c) => (
            <PersonCard key={c.id} id={c.id} name={c.name} meta={`🎂 Lahir ${formatDate(c.birthday)}`}>
              <WhatsAppButton customer={c} templates={templates} size="sm" label="Kirim ucapan" preferCategory="Ulang tahun" className="w-full" />
            </PersonCard>
          ))}
        </Section>
      )}

      {data.inactive.length > 0 && (
        <Section title="Lama tidak belanja" count={data.inactive.length} icon={Clock}>
          {data.inactive.map((c) => (
            <PersonCard
              key={c.id}
              id={c.id}
              name={c.name}
              meta={`Terakhir beli ${c.lastOrderAt ? relativeDays(c.lastOrderAt, now) : "-"} · total ${formatRupiah(num(c.totalSpent))}`}
            >
              <WhatsAppButton customer={c} templates={templates} size="sm" label="Sapa lagi" preferCategory="Pengingat" variant="secondary" className="w-full" />
            </PersonCard>
          ))}
        </Section>
      )}
    </>
  );
}

function Counter({ label, value, alert }: { label: string; value: number; alert?: boolean }) {
  return (
    <div className={"rounded-2xl border p-3 " + (alert ? "border-red-200 bg-red-50" : "border-zinc-200")}>
      <p className={"tabular text-2xl font-semibold " + (alert ? "text-red-700" : "")}>{value}</p>
      <p className="text-xs text-zinc-500">{label}</p>
    </div>
  );
}

function Section({ title, count, icon: Icon, children }: { title: string; count: number; icon: React.ElementType; children: React.ReactNode }) {
  return (
    <section className="mb-6">
      <SectionTitle count={count}>
        <Icon className="mr-1 inline h-3.5 w-3.5" />
        {title}
      </SectionTitle>
      <ul className="space-y-2">{children}</ul>
    </section>
  );
}

function PersonCard({ id, name, meta, children }: { id: string; name: string; meta: string; children: React.ReactNode }) {
  return (
    <li className="rounded-2xl border border-zinc-200 p-4">
      <Link href={`/pelanggan/${id}`} className="mb-3 flex items-center gap-3">
        <Avatar name={name} size={36} />
        <div className="min-w-0">
          <p className="truncate font-medium">{name}</p>
          <p className="truncate text-sm text-zinc-500">{meta}</p>
        </div>
      </Link>
      {children}
    </li>
  );
}
