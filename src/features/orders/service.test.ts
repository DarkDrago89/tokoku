import { describe, expect, it } from "vitest";
import { prisma } from "@/lib/db";
import { makeStore, randomPhone } from "@/test/factory";
import { createCustomerForStore } from "@/features/customers/service";
import { createOrderForStore, duplicateOrderForStore, updateOrderStatusForStore } from "./service";

async function setup() {
  const s = await makeStore();
  const c = await createCustomerForStore(s.storeId, { name: "Ani", phone: randomPhone() });
  return { ...s, customerId: c.id };
}

const item = { itemName: "Kopi Gayo 250g", qty: 2, unitPrice: 50000 };

describe("layanan pesanan", () => {
  it("nomor pesanan berurutan per toko", async () => {
    const s = await setup();
    const o1 = await createOrderForStore(s.storeId, { customerId: s.customerId, items: [item] });
    const o2 = await createOrderForStore(s.storeId, { customerId: s.customerId, items: [item] });
    expect([o1.orderNumber, o2.orderNumber]).toEqual(["INV-0001", "INV-0002"]);
  });

  it("menghitung total dari item, diskon, ongkir", async () => {
    const s = await setup();
    const o = await createOrderForStore(s.storeId, {
      customerId: s.customerId,
      items: [item],
      discount: 10000,
      shippingCost: 15000,
    });
    expect(o.total.toNumber()).toBe(105000);
  });

  it("Selesai menambah total belanja dan membuat tugas minta ulasan; Batal menguranginya", async () => {
    const s = await setup();
    const o = await createOrderForStore(s.storeId, { customerId: s.customerId, items: [item] });
    await updateOrderStatusForStore(s.storeId, o.id, "done", { userId: s.userId });
    let c = await prisma.customer.findUniqueOrThrow({ where: { id: s.customerId } });
    expect(c.totalSpent.toNumber()).toBe(100000);
    expect(c.orderCount).toBe(1);
    const tasks = await prisma.task.findMany({ where: { customerId: s.customerId, autoGenerated: true } });
    expect(tasks.map((t) => t.title)).toEqual(["Minta ulasan"]);
    const due = Math.round((+tasks[0].dueDate - +new Date(new Date().toISOString().slice(0, 10))) / 86_400_000);
    expect(due).toBeGreaterThanOrEqual(2);
    expect(due).toBeLessThanOrEqual(4);

    await updateOrderStatusForStore(s.storeId, o.id, "cancelled", { userId: s.userId });
    c = await prisma.customer.findUniqueOrThrow({ where: { id: s.customerId } });
    expect(c.totalSpent.toNumber()).toBe(0);
    expect(c.orderCount).toBe(0);
  });

  it("menyimpan nomor resi saat dikirim", async () => {
    const s = await setup();
    const o = await createOrderForStore(s.storeId, { customerId: s.customerId, items: [item] });
    const u = await updateOrderStatusForStore(s.storeId, o.id, "shipped", { trackingNumber: "JNE123", userId: s.userId });
    expect(u.trackingNumber).toBe("JNE123");
  });

  it("pesan ulang menyalin item menjadi pesanan baru berstatus Menunggu Bayar", async () => {
    const s = await setup();
    const o = await createOrderForStore(s.storeId, { customerId: s.customerId, items: [item], shippingCost: 9000 });
    await updateOrderStatusForStore(s.storeId, o.id, "done", { userId: s.userId });
    const copy = await duplicateOrderForStore(s.storeId, o.id);
    expect(copy.status).toBe("pending");
    expect(copy.orderNumber).toBe("INV-0002");
    const items = await prisma.orderItem.findMany({ where: { orderId: copy.id } });
    expect(items).toHaveLength(1);
    expect(copy.total.toNumber()).toBe(109000);
  });

  it("tidak bisa membuat pesanan untuk pelanggan toko lain", async () => {
    const a = await setup();
    const b = await makeStore();
    await expect(createOrderForStore(b.storeId, { customerId: a.customerId, items: [item] })).rejects.toThrow();
  });
});

describe("penomoran setelah INV-9999", () => {
  it("lanjut ke INV-10000 lalu INV-10001", async () => {
    const s = await setup();
    const o = await createOrderForStore(s.storeId, { customerId: s.customerId, items: [item] });
    await prisma.order.update({ where: { id: o.id }, data: { orderNumber: "INV-9999" } });
    const a = await createOrderForStore(s.storeId, { customerId: s.customerId, items: [item] });
    const b = await createOrderForStore(s.storeId, { customerId: s.customerId, items: [item] });
    expect([a.orderNumber, b.orderNumber]).toEqual(["INV-10000", "INV-10001"]);
  });
});
